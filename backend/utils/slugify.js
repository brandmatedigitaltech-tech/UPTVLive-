const createSlug = (
  text = ""
) => {

  // =====================================================
  // ================= SAFE STRING =======================
  // =====================================================

  let slug = String(text)
    .trim()
    .toLowerCase();

  // =====================================================
  // ================= REMOVE HTML =======================
  // =====================================================

  slug = slug.replace(
    /<[^>]*>/g,
    ""
  );

  // =====================================================
  // ================= HINDI TO ENGLISH ==================
  // =====================================================

  const hindiMap = {

    "अ": "a",
    "आ": "aa",
    "इ": "i",
    "ई": "ee",
    "उ": "u",
    "ऊ": "oo",
    "ए": "e",
    "ऐ": "ai",
    "ओ": "o",
    "औ": "au",

    "क": "k",
    "ख": "kh",
    "ग": "g",
    "घ": "gh",

    "च": "ch",
    "छ": "chh",
    "ज": "j",
    "झ": "jh",

    "ट": "t",
    "ठ": "th",
    "ड": "d",
    "ढ": "dh",

    "त": "t",
    "थ": "th",
    "द": "d",
    "ध": "dh",
    "न": "n",

    "प": "p",
    "फ": "ph",
    "ब": "b",
    "भ": "bh",
    "म": "m",

    "य": "y",
    "र": "r",
    "ल": "l",
    "व": "v",

    "श": "sh",
    "ष": "sh",
    "स": "s",
    "ह": "h",

    "ा": "a",
    "ि": "i",
    "ी": "ee",
    "ु": "u",
    "ू": "oo",
    "े": "e",
    "ै": "ai",
    "ो": "o",
    "ौ": "au",

    "ं": "n",
    "ः": "",
    "्": "",

  };

  slug = slug
    .split("")
    .map(
      (char) =>
        hindiMap[char] || char
    )
    .join("");

  // =====================================================
  // ================= REMOVE SPECIAL ====================
  // =====================================================

  slug = slug.replace(
    /[^a-z0-9\s-]/gi,
    ""
  );

  // =====================================================
  // ================= SPACE TO DASH =====================
  // =====================================================

  slug = slug.replace(
    /\s+/g,
    "-"
  );

  // =====================================================
  // ================= CLEAN DASHES ======================
  // =====================================================

  slug = slug.replace(
    /-+/g,
    "-"
  );

  slug = slug.replace(
    /^-+|-+$/g,
    ""
  );

  // =====================================================
  // ================= LIMIT LENGTH ======================
  // =====================================================

  slug = slug.substring(
    0,
    120
  );

  // =====================================================
  // ================= FALLBACK ==========================
  // =====================================================

  if (
    !slug ||
    slug.trim() === ""
  ) {

    slug =
      `news-${Date.now()}`;
  }

  return slug;
};

module.exports =
  createSlug;
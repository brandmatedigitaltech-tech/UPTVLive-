const createSlug = (
  text = ""
) => {

  // =====================================================
  // ================= SAFE STRING =======================
  // =====================================================

  let slug = String(text)
    .trim()
    .toLowerCase();

  // =====================================================
  // ================= NORMALIZE =========================
  // =====================================================

  slug = slug.normalize("NFC");

  // =====================================================
  // ================= REMOVE HTML =======================
  // =====================================================

  slug = slug.replace(
    /<[^>]*>/g,
    ""
  );

  // =====================================================
  // ================= REMOVE SPECIAL ====================
  // =====================================================

  // ✅ KEEP:
  // Hindi
  // English
  // Numbers
  // Spaces
  // Dash

  slug = slug.replace(
    /[^\u0900-\u097Fa-z0-9\s-]/gi,
    ""
  );

  // =====================================================
  // ================= SPACE TO DASH =====================
  // =====================================================

  slug = slug.replace(
    /\s+/g,
    "-"
  );

  // =====================================================
  // ================= CLEAN MULTIPLE DASH ===============
  // =====================================================

  slug = slug.replace(
    /-+/g,
    "-"
  );

  // =====================================================
  // ================= REMOVE START/END DASH =============
  // =====================================================

  slug = slug.replace(
    /^-+|-+$/g,
    ""
  );

  // =====================================================
  // ================= LIMIT LENGTH ======================
  // =====================================================

  slug = slug.substring(
    0,
    120
  );

  // =====================================================
  // ================= FINAL CLEAN =======================
  // =====================================================

  slug = slug.replace(
    /^-+|-+$/g,
    ""
  );

  // =====================================================
  // ================= FALLBACK ==========================
  // =====================================================

  if (
    !slug ||
    slug.trim() === ""
  ) {

    slug =
      `news-${Date.now()}`;
  }

  return slug;
};

module.exports =
  createSlug;
const createSlug = (
  text = ""
) => {

  // =====================================================
  // ================= SAFE STRING =======================
  // =====================================================

  let slug = String(
    text
  )
    .trim()
    .toLowerCase();

  // =====================================================
  // ================= REMOVE HTML =======================
  // =====================================================

  slug = slug.replace(
    /<[^>]*>/g,
    ""
  );

  // =====================================================
  // ================= REMOVE SPECIAL ====================
  // =====================================================

  // ✅ KEEP:
  // Hindi
  // English
  // Numbers
  // Spaces
  // Dash

  slug = slug.replace(
    /[^\u0900-\u097Fa-z0-9\s-]/gi,
    ""
  );

  // =====================================================
  // ================= SPACE TO DASH =====================
  // =====================================================

  slug = slug.replace(
    /\s+/g,
    "-"
  );

  // =====================================================
  // ================= CLEAN DASHES ======================
  // =====================================================

  slug = slug.replace(
    /-+/g,
    "-"
  );

  slug = slug.replace(
    /^-+|-+$/g,
    ""
  );

  // =====================================================
  // ================= LIMIT =============================
  // =====================================================

  slug = slug.substring(
    0,
    150
  );

  // =====================================================
  // ================= FALLBACK ==========================
  // =====================================================

  if (
    !slug ||
    slug.trim() === ""
  ) {
    slug = `news-${Date.now()}`;
  }

  return slug;
};

module.exports =
  createSlug;